#BasicOperations
a = 10
b = 3
print("Add:", a + b)                # +  Add
print("Subtract:", a - b)           # -  Subtract
print("Multiply:", a * b)           # *  Multiply
print("Divide:", a / b)             # /  Divide
print("Floor Division:", a // b)    # // Floor Division
print("Modulus:", a % b)            # %  Modulus
print("Power:", a ** b)             #**  Power
